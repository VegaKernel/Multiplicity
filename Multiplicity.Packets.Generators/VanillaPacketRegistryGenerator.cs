using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Multiplicity.Packets.Generators
{
    [Generator]
    public sealed class VanillaPacketRegistryGenerator : IIncrementalGenerator
    {
        private const string PacketNamespace = "Multiplicity.Packets";
        private const string PacketBaseMetadataName = "Multiplicity.Packets.TerrariaPacket";
        private const string PacketTypesMetadataName = "Multiplicity.Packets.PacketTypes";
        private const string IgnoreAttributeMetadataName = "Multiplicity.Packets.PacketRegistrationIgnoreAttribute";
        private const string BinaryReaderMetadataName = "System.IO.BinaryReader";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            IncrementalValuesProvider<INamedTypeSymbol?> candidates = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) => ctx.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)ctx.Node) as INamedTypeSymbol);

            IncrementalValueProvider<(Compilation Compilation, ImmutableArray<INamedTypeSymbol?> Types)> input =
                context.CompilationProvider.Combine(candidates.Collect());

            context.RegisterSourceOutput(input, static (spc, pair) =>
            {
                string source = Generate(pair.Compilation, pair.Types);
                spc.AddSource("VanillaPacketRegistry.g.cs", SourceText.From(source, Encoding.UTF8));
            });
        }

        private static string Generate(Compilation compilation, ImmutableArray<INamedTypeSymbol?> candidates)
        {
            INamedTypeSymbol? packetBase = compilation.GetTypeByMetadataName(PacketBaseMetadataName);
            INamedTypeSymbol? packetTypes = compilation.GetTypeByMetadataName(PacketTypesMetadataName);
            INamedTypeSymbol? ignoreAttribute = compilation.GetTypeByMetadataName(IgnoreAttributeMetadataName);
            INamedTypeSymbol? binaryReader = compilation.GetTypeByMetadataName(BinaryReaderMetadataName);

            if (packetBase == null || packetTypes == null || binaryReader == null)
            {
                return EmptyRegistrySource();
            }

            Dictionary<string, int> packetIds = new Dictionary<string, int>(StringComparer.Ordinal);
            foreach (ISymbol member in packetTypes.GetMembers())
            {
                if (member is IFieldSymbol field && field.HasConstantValue && field.ConstantValue is byte value)
                {
                    packetIds[field.Name] = value;
                }
            }

            List<PacketModel> models = new List<PacketModel>();
            HashSet<string> seen = new HashSet<string>(StringComparer.Ordinal);

            foreach (INamedTypeSymbol? type in candidates)
            {
                if (type == null || type.IsAbstract || type.TypeKind != TypeKind.Class)
                {
                    continue;
                }

                if (!string.Equals(type.ContainingNamespace?.ToDisplayString(), PacketNamespace, StringComparison.Ordinal))
                {
                    continue;
                }

                if (!DerivesFrom(type, packetBase))
                {
                    continue;
                }

                if (ignoreAttribute != null && type.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, ignoreAttribute)))
                {
                    continue;
                }

                if (!packetIds.TryGetValue(type.Name, out int packetId))
                {
                    continue;
                }

                if (!HasParameterlessConstructor(type) || !HasBinaryReaderConstructor(type, binaryReader))
                {
                    continue;
                }

                string fullName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                if (!seen.Add(fullName))
                {
                    continue;
                }

                bool isFixed = IsFixedPayload(type);
                models.Add(new PacketModel(type.Name, fullName, packetId, isFixed));
            }

            models.Sort(static (a, b) => a.PacketId.CompareTo(b.PacketId));

            StringBuilder sb = new StringBuilder(32768);
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using System.IO;");
            sb.AppendLine();
            sb.AppendLine("namespace Multiplicity.Packets");
            sb.AppendLine("{");
            sb.AppendLine("    internal static class VanillaPacketRegistry");
            sb.AppendLine("    {");
            sb.AppendLine("        private static readonly PacketRegistration[] Registrations =");
            sb.AppendLine("        {");

            foreach (PacketModel model in models)
            {
                string factory = model.IsFixed ? "PacketRegistration.Fixed" : "PacketRegistration.Variable";
                sb.Append("            ")
                    .Append(factory)
                    .Append("(PacketTypes.")
                    .Append(model.PacketTypeName)
                    .Append(", static br => new ")
                    .Append(model.FullTypeName)
                    .Append("(br), static () => new ")
                    .Append(model.FullTypeName)
                    .AppendLine("()),");
            }

            sb.AppendLine("        };");
            sb.AppendLine();
            sb.AppendLine("        public static Dictionary<PacketTypes, Func<BinaryReader, TerrariaPacket>> CreateDeserializerMap()");
            sb.AppendLine("        {");
            sb.AppendLine("            var map = new Dictionary<PacketTypes, Func<BinaryReader, TerrariaPacket>>(Registrations.Length);");
            sb.AppendLine("            for (int i = 0; i < Registrations.Length; i++)");
            sb.AppendLine("            {");
            sb.AppendLine("                PacketRegistration registration = Registrations[i];");
            sb.AppendLine("                map.Add(registration.PacketType, registration.Deserialize);");
            sb.AppendLine("            }");
            sb.AppendLine("            return map;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public static IReadOnlyDictionary<PacketTypes, PacketPayloadMetadata> CreatePayloadMetadataMap()");
            sb.AppendLine("        {");
            sb.AppendLine("            var map = new Dictionary<PacketTypes, PacketPayloadMetadata>(Registrations.Length);");
            sb.AppendLine("            for (int i = 0; i < Registrations.Length; i++)");
            sb.AppendLine("            {");
            sb.AppendLine("                PacketRegistration registration = Registrations[i];");
            sb.AppendLine("                map.Add(registration.PacketType, registration.CreateMetadata());");
            sb.AppendLine("            }");
            sb.AppendLine("            return map;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static bool DerivesFrom(INamedTypeSymbol type, INamedTypeSymbol packetBase)
        {
            for (INamedTypeSymbol? current = type.BaseType; current != null; current = current.BaseType)
            {
                if (SymbolEqualityComparer.Default.Equals(current, packetBase))
                {
                    return true;
                }
            }

            return false;
        }

        private static bool HasParameterlessConstructor(INamedTypeSymbol type)
        {
            return type.InstanceConstructors.Any(static ctor =>
                !ctor.IsStatic &&
                ctor.Parameters.Length == 0 &&
                ctor.DeclaredAccessibility != Accessibility.Private);
        }

        private static bool HasBinaryReaderConstructor(INamedTypeSymbol type, INamedTypeSymbol binaryReader)
        {
            return type.InstanceConstructors.Any(ctor =>
                !ctor.IsStatic &&
                ctor.Parameters.Length == 1 &&
                SymbolEqualityComparer.Default.Equals(ctor.Parameters[0].Type, binaryReader) &&
                ctor.DeclaredAccessibility != Accessibility.Private);
        }

        private static bool IsFixedPayload(INamedTypeSymbol type)
        {
            // Historically FixedPayloadLength means a mandatory prefix of a variable packet,
            // while PayloadLength means the entire payload is fixed. Preserve that convention.
            if (FindConstShort(type, "FixedPayloadLength"))
            {
                return false;
            }

            return FindConstShort(type, "PayloadLength");
        }

        private static bool FindConstShort(INamedTypeSymbol type, string fieldName)
        {
            for (INamedTypeSymbol? current = type; current != null; current = current.BaseType)
            {
                foreach (ISymbol member in current.GetMembers(fieldName))
                {
                    if (member is IFieldSymbol field &&
                        field.IsConst &&
                        field.Type.SpecialType == SpecialType.System_Int16)
                    {
                        return true;
                    }
                }
            }

            return false;
        }

        private static string EmptyRegistrySource()
        {
            return @"// <auto-generated />
using System;
using System.Collections.Generic;
using System.IO;
namespace Multiplicity.Packets
{
    internal static class VanillaPacketRegistry
    {
        public static Dictionary<PacketTypes, Func<BinaryReader, TerrariaPacket>> CreateDeserializerMap() => new();
        public static IReadOnlyDictionary<PacketTypes, PacketPayloadMetadata> CreatePayloadMetadataMap() => new Dictionary<PacketTypes, PacketPayloadMetadata>();
    }
}";
        }

        private sealed class PacketModel
        {
            public PacketModel(string packetTypeName, string fullTypeName, int packetId, bool isFixed)
            {
                PacketTypeName = packetTypeName;
                FullTypeName = fullTypeName;
                PacketId = packetId;
                IsFixed = isFixed;
            }

            public string PacketTypeName { get; }
            public string FullTypeName { get; }
            public int PacketId { get; }
            public bool IsFixed { get; }
        }
    }
}
